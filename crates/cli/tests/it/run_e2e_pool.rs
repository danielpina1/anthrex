//! Milestone 9.14 task M9.14.6: the target pool end to end, through a real daemon with
//! `fake-agent` as the workers and reviewers. A stored profile says
//! `CARGO_TARGET_DIR = "{worktree}/target"`, so every checkout's builds go to a
//! directory leased from `<repo_dir>/target-pool/`; the `check` writes a marker into
//! `$CARGO_TARGET_DIR` so the test can see where it ran. The repository is a tiny
//! cargo workspace with no dependency (the shared test rules), which only the release's
//! `cargo metadata --offline` reads; nothing builds it.
//!
//! Timing: each wait is `RUN_WAIT` (`run_harness.rs`), plus the pool's own worst case
//! on the critical path: one `POOL_CLEAN_TIMEOUT` (120 s, `daemon::run::target_pool`)
//! per release before a task's merge completes, so `RUN_WAIT + k × POOL_CLEAN_TIMEOUT`
//! for `k` tasks (milestone 9.14 brief, M9.14.10's rows).

use crate::support;

use std::path::{Path, PathBuf};
use std::time::Duration;

use daemon::run::target_pool::{
    DirState, LeasesFile, POOL_CLEAN_TIMEOUT, POOL_DIR_NAME, POOL_LEASES_FILE, PoolClass,
};
use proto::{FinishAction, RunReply, RunRequest, RunState, TaskState};
use support::run_harness::{RUN_WAIT, RunHarness};
use support::run_plans::*;
use support::run_pr::log_lines;

/// The stored profile: a `check` that writes `ran-<task>` (`b.txt` is t2's, `a.txt`
/// t1's) into `$CARGO_TARGET_DIR`, and the per-checkout target directory.
const POOL_PROFILE: &str = "check = \"sh check.sh\"\ncheck_timeout_secs = 10\n\n[env]\nCARGO_TARGET_DIR = \"{worktree}/target\"\n";

const CHECK_SH: &str = "mkdir -p \"$CARGO_TARGET_DIR\"\n\
if [ -e b.txt ]; then t=t2; elif [ -e a.txt ]; then t=t1; else exit 0; fi\n\
: > \"$CARGO_TARGET_DIR/ran-$t\"\n";

/// The repository is a one-package cargo workspace with its lock file and no
/// dependency, so a release's `cargo metadata --offline --locked` succeeds and the
/// clean keeps the directory (a failed one would wipe it, markers and all).
const WORKSPACE: &[(&str, &str)] = &[
    (
        "Cargo.toml",
        "[package]\nname = \"pool-app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    ),
    (
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"pool-app\"\nversion = \"0.1.0\"\n",
    ),
    ("src/lib.rs", "pub fn f() {}\n"),
    ("check.sh", CHECK_SH),
];

fn wait_for(tasks: u32) -> Duration {
    RUN_WAIT + POOL_CLEAN_TIMEOUT * tasks
}

/// A harness with `orchestrator` lines, `[target_pool]` lines and the profile stored.
fn harness(orchestrator: &str, pool: &str) -> RunHarness {
    let h = RunHarness::with_config(orchestrator, &format!("[target_pool]\n{pool}"), WORKSPACE);
    h.stored_profile(POOL_PROFILE);
    h
}

/// A plan with no `[profile]`: the stored profile is the run's.
fn plan_of(tasks: &[String]) -> String {
    format!("goal = \"Pool\"\n{}", tasks.concat())
}

fn scripts(h: &RunHarness, id: &str, file: &str) {
    h.script(
        &format!("worker-{id}-1"),
        &[commit(file, "x\n"), done(&format!("added {file}"))],
    );
    h.script(&format!("reviewer-{id}-1"), &[approve()]);
}

fn pool_root(h: &RunHarness) -> PathBuf {
    h.repo_dir().join(POOL_DIR_NAME)
}

/// Every pool directory holding `ran-<task>`.
fn ran_in(h: &RunHarness, task: &str) -> Vec<String> {
    let mut found: Vec<String> = std::fs::read_dir(pool_root(h))
        .unwrap()
        .flatten()
        .filter(|e| e.path().join(format!("ran-{task}")).exists())
        .filter_map(|e| e.file_name().to_str().map(str::to_string))
        .collect();
    found.sort();
    found
}

fn leases(h: &RunHarness) -> LeasesFile {
    let text = std::fs::read_to_string(pool_root(h).join(POOL_LEASES_FILE)).unwrap();
    serde_json::from_str(&text).unwrap()
}

fn pool_notes(h: &RunHarness, id: &str) -> Vec<String> {
    (log_lines(h, id).into_iter())
        .filter(|l| l.starts_with("target pool: "))
        .collect()
}

fn accept(h: &RunHarness, id: &str) {
    match h.request(RunRequest::Finish {
        run_id: id.to_string(),
        action: FinishAction::Accept,
        confirm: Some(id.to_string()),
    }) {
        RunReply::Done { .. } => {}
        other => panic!("expected the accept, got {other:?}"),
    }
}

/// No `target` under any of the run's checkouts that still exist.
fn no_worktree_target(worktree: &Path) {
    assert!(
        !worktree.join("target").exists(),
        "{} built in its own target directory",
        worktree.display()
    );
}

#[test]
fn e2e_a_task_builds_in_a_leased_dir_and_releases_it() {
    let h = harness("", "");
    scripts(&h, "t1", "a.txt");
    let id = h.start(&plan_of(&[task("t1", &["a.txt"], "")]), true);
    let run = h.wait_run(&id, complete, wait_for(1));
    assert_eq!(t(&run, "t1").state, TaskState::Merged);
    let ran = ran_in(&h, "t1");
    assert!(
        ran.iter().any(|d| d.starts_with("task-")),
        "ran-t1 is in a task directory: {ran:?}"
    );
    no_worktree_target(&integration(t(&run, "t1")));

    accept(&h, &id);
    h.wait_run(&id, |r| r.state == RunState::Accepted, wait_for(1));
    let leased: Vec<_> = (leases(&h).dirs.into_iter())
        .filter(|d| d.state == DirState::Leased)
        .collect();
    assert!(
        leased.is_empty(),
        "still leased after the accept: {leased:?}"
    );
    assert_eq!(pool_notes(&h, &id), Vec::<String>::new());
}

/// The pool's `leases.json` once it exists.
fn leases_now(h: &RunHarness) -> Option<LeasesFile> {
    let text = std::fs::read_to_string(pool_root(h).join(POOL_LEASES_FILE)).ok()?;
    serde_json::from_str(&text).ok()
}

/// The task directory leased by the checkout named `checkout` (`t2`, `t1.proof`).
fn held_by(leases: &LeasesFile, checkout: &str) -> Option<String> {
    (leases.dirs.iter())
        .filter(|d| d.class == PoolClass::Task && d.state == DirState::Leased)
        .find(|d| (d.owner.as_deref()).is_some_and(|o| o.file_name() == Some(checkout.as_ref())))
        .map(|d| format!("task-{}", d.k))
}

/// C14: one writer and two task directories (a task worktree and its `.proof` are
/// different owners, decision 4, and the `check` runs in `.proof`). t1's worktree and
/// its `.proof` take both; t2's `.proof` builds in one of them after their release.
///
/// Deviation from the brief (recorded in its implementation notes): `remove_merged`'s
/// releases and t2's `PrepareWorktree` are emitted by the same merge step and run
/// concurrently, and a release cleans before it frees, so t2's worktree may lease while
/// both directories are still t1's and fall back (decision 7: one note, for `t2`).
/// Nothing in the test can order that lease. t2's `.proof` is ordered (task-6 review
/// I1): t2's worker waits, before its `task_done`, for a gate the test opens only once
/// t1 is merged and `leases.json` shows no lease of `t1` or `t1.proof`. Its `.proof`
/// is prepared after `task_done`, so it always finds t1's directories free.
#[test]
fn e2e_a_second_task_reuses_the_released_dir() {
    let h = harness("max_writers = 1\n", "task_dirs = 2\n");
    scripts(&h, "t1", "a.txt");
    // Timing: t1 runs, merges and releases its two directories within `wait_for(2)`
    // (`RUN_WAIT` for the task, one `POOL_CLEAN_TIMEOUT` per release, see the file's
    // header); the worker's own wait has the same bound, in 0.1 s polls.
    let gate = h.dir.path().join("t2-gate");
    let polls = wait_for(2).as_millis() / 100;
    let wait_gate = format!(
        "i=0; until [ -e '{}' ]; do i=$((i+1)); [ $i -gt {polls} ] && exit 1; sleep 0.1; done",
        gate.display()
    );
    h.script(
        "worker-t2-1",
        &[commit("b.txt", "x\n"), sh(&wait_gate), done("added b.txt")],
    );
    h.script("reviewer-t2-1", &[approve()]);
    let plan = plan_of(&[
        task("t1", &["a.txt"], ""),
        task("t2", &["b.txt"], "deps = [\"t1\"]"),
    ]);
    let fell_back =
        "target pool: no free task directory for t2; it builds in its own target directory";
    let id = h.start(&plan, true);
    // Open the gate once t1 is merged, neither of its checkouts holds a directory, and
    // t2's worktree lease is decided: a directory held, or its fallback note logged.
    let t2_worktree_dir = until("t1's releases and t2's lease", wait_for(2), || {
        let run = h.run(&id)?;
        if t(&run, "t1").state != TaskState::Merged {
            return None;
        }
        let leases = leases_now(&h)?;
        let t1_held = ["t1", "t1.proof"]
            .iter()
            .any(|c| held_by(&leases, c).is_some());
        let held = held_by(&leases, "t2");
        let noted = pool_notes(&h, &id).iter().any(|n| n == fell_back);
        (!t1_held && (held.is_some() || noted)).then_some(held)
    });
    std::fs::write(&gate, b"").unwrap();

    let run = h.wait_run(&id, complete, wait_for(2));
    assert_eq!(t(&run, "t2").state, TaskState::Merged);
    let task_dirs = |dirs: Vec<String>| -> Vec<String> {
        dirs.into_iter()
            .filter(|d| d.starts_with("task-"))
            .collect()
    };
    let (t1, t2) = (task_dirs(ran_in(&h, "t1")), task_dirs(ran_in(&h, "t2")));
    assert_eq!(t1.len(), 1, "t1's check built in the pool: {t1:?}");
    assert_eq!(t2.len(), 1, "t2's check built in the pool: {t2:?}");
    let notes = pool_notes(&h, &id);
    match t2_worktree_dir {
        // t2's worktree leased one of t1's released directories, so its `.proof` got
        // the other: decision 5's choice, observed. When the worktree took t1's
        // worktree directory, t2's check builds where t1's check built (F8).
        Some(held) => {
            assert_eq!(notes, Vec::<String>::new());
            let other = if held == "task-1" { "task-2" } else { "task-1" };
            assert_eq!(t2, [other], "t2's worktree holds {held}");
        }
        // The race above (the usual case): one note, for t2's worktree alone, never for
        // its `.proof`. Which of t1's two free directories the `.proof` gets is decision
        // 5's least-recently-used choice between two releases that may end in the same
        // second, so it is not pinned (recorded as a 9.14 follow-up).
        None => assert_eq!(notes, [fell_back]),
    }
}

//! Milestone 9.14 task M9.14.6: the target pool end to end, through a real daemon with
//! `fake-agent` as the workers and reviewers. A stored profile says
//! `CARGO_TARGET_DIR = "{worktree}/target"`, so every checkout's builds go to a
//! directory leased from `<repo_dir>/target-pool/`; the `check` writes a marker into
//! `$CARGO_TARGET_DIR` so the test can see where it ran. The repository is a tiny
//! cargo workspace with no dependency (the shared test rules). In the first two
//! scenarios only the release's `cargo metadata --offline` reads it; the C14 scenario
//! builds its own one-crate workspace with real `cargo --offline`.
//!
//! Timing: each wait is `RUN_WAIT` (`run_harness.rs`), plus the pool's own worst case
//! on the critical path: one `POOL_CLEAN_TIMEOUT` (120 s, `daemon::run::target_pool`)
//! per release before a task's merge completes, so `RUN_WAIT + k × POOL_CLEAN_TIMEOUT`
//! for `k` tasks (milestone 9.14 brief, M9.14.10's rows).

use crate::support;

use std::path::{Path, PathBuf};
use std::time::Duration;

use daemon::run::target_pool::{
    DirState, LeasesFile, POOL_CLEAN_TIMEOUT, POOL_DIR_NAME, POOL_LEASES_FILE, PoolClass,
};
use proto::{FinishAction, RunReply, RunRequest, RunState, TaskState};
use serde_json::Value;
use support::run_harness::{CHECK_TIMEOUT_SECS, RUN_WAIT, RunHarness};
use support::run_plans::*;
use support::run_pr::log_lines;

/// The stored profile: a `check` that writes `ran-<task>` (`b.txt` is t2's, `a.txt`
/// t1's) into `$CARGO_TARGET_DIR`, and the per-checkout target directory.
const POOL_PROFILE: &str = "check = \"sh check.sh\"\ncheck_timeout_secs = 10\n\n[env]\nCARGO_TARGET_DIR = \"{worktree}/target\"\n";

const CHECK_SH: &str = "mkdir -p \"$CARGO_TARGET_DIR\"\n\
if [ -e b.txt ]; then t=t2; elif [ -e a.txt ]; then t=t1; else exit 0; fi\n\
: > \"$CARGO_TARGET_DIR/ran-$t\"\n";

/// The repository is a one-package cargo workspace with its lock file and no
/// dependency, so a release's `cargo metadata --offline --locked` succeeds and the
/// clean keeps the directory (a failed one would wipe it, markers and all).
const WORKSPACE: &[(&str, &str)] = &[
    (
        "Cargo.toml",
        "[package]\nname = \"pool-app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    ),
    (
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"pool-app\"\nversion = \"0.1.0\"\n",
    ),
    ("src/lib.rs", "pub fn f() {}\n"),
    ("check.sh", CHECK_SH),
];

fn wait_for(tasks: u32) -> Duration {
    RUN_WAIT + POOL_CLEAN_TIMEOUT * tasks
}

/// A harness with `orchestrator` lines, `[target_pool]` lines and the profile stored.
fn harness(orchestrator: &str, pool: &str) -> RunHarness {
    let h = RunHarness::with_config(orchestrator, &format!("[target_pool]\n{pool}"), WORKSPACE);
    h.stored_profile(POOL_PROFILE);
    h
}

/// A plan with no `[profile]`: the stored profile is the run's.
fn plan_of(tasks: &[String]) -> String {
    format!("goal = \"Pool\"\n{}", tasks.concat())
}

fn scripts(h: &RunHarness, id: &str, file: &str) {
    h.script(
        &format!("worker-{id}-1"),
        &[commit(file, "x\n"), done(&format!("added {file}"))],
    );
    h.script(&format!("reviewer-{id}-1"), &[approve()]);
}

fn pool_root(h: &RunHarness) -> PathBuf {
    h.repo_dir().join(POOL_DIR_NAME)
}

/// Every pool directory holding `ran-<task>`.
fn ran_in(h: &RunHarness, task: &str) -> Vec<String> {
    let mut found: Vec<String> = std::fs::read_dir(pool_root(h))
        .unwrap()
        .flatten()
        .filter(|e| e.path().join(format!("ran-{task}")).exists())
        .filter_map(|e| e.file_name().to_str().map(str::to_string))
        .collect();
    found.sort();
    found
}

fn leases(h: &RunHarness) -> LeasesFile {
    let text = std::fs::read_to_string(pool_root(h).join(POOL_LEASES_FILE)).unwrap();
    serde_json::from_str(&text).unwrap()
}

fn pool_notes(h: &RunHarness, id: &str) -> Vec<String> {
    (log_lines(h, id).into_iter())
        .filter(|l| l.starts_with("target pool: "))
        .collect()
}

fn accept(h: &RunHarness, id: &str) {
    match h.request(RunRequest::Finish {
        run_id: id.to_string(),
        action: FinishAction::Accept,
        confirm: Some(id.to_string()),
        reason: None,
    }) {
        RunReply::Done { .. } => {}
        other => panic!("expected the accept, got {other:?}"),
    }
}

/// No `target` under any of the run's checkouts that still exist.
fn no_worktree_target(worktree: &Path) {
    assert!(
        !worktree.join("target").exists(),
        "{} built in its own target directory",
        worktree.display()
    );
}

#[test]
fn e2e_a_task_builds_in_a_leased_dir_and_releases_it() {
    let h = harness("", "");
    scripts(&h, "t1", "a.txt");
    let id = h.start(&plan_of(&[task("t1", &["a.txt"], "")]), true);
    let run = h.wait_run(&id, complete, wait_for(1));
    assert_eq!(t(&run, "t1").state, TaskState::Merged);
    let ran = ran_in(&h, "t1");
    assert!(
        ran.iter().any(|d| d.starts_with("task-")),
        "ran-t1 is in a task directory: {ran:?}"
    );
    no_worktree_target(&integration(t(&run, "t1")));

    accept(&h, &id);
    h.wait_run(&id, |r| r.state == RunState::Accepted, wait_for(1));
    let leased: Vec<_> = (leases(&h).dirs.into_iter())
        .filter(|d| d.state == DirState::Leased)
        .collect();
    assert!(
        leased.is_empty(),
        "still leased after the accept: {leased:?}"
    );
    assert_eq!(pool_notes(&h, &id), Vec::<String>::new());
}

/// The pool's `leases.json` once it exists.
fn leases_now(h: &RunHarness) -> Option<LeasesFile> {
    let text = std::fs::read_to_string(pool_root(h).join(POOL_LEASES_FILE)).ok()?;
    serde_json::from_str(&text).ok()
}

/// The task directory leased by the checkout named `checkout` (`t2`, `t1.proof`).
fn held_by(leases: &LeasesFile, checkout: &str) -> Option<String> {
    (leases.dirs.iter())
        .filter(|d| d.class == PoolClass::Task && d.state == DirState::Leased)
        .find(|d| (d.owner.as_deref()).is_some_and(|o| o.file_name() == Some(checkout.as_ref())))
        .map(|d| format!("task-{}", d.k))
}

/// The fallback note of t2's worktree (decision 7).
const T2_FELL_BACK: &str =
    "target pool: no free task directory for t2; it builds in its own target directory";

/// The `sh` step t2's worker runs before its `task_done`: it waits for `gate`.
///
/// Timing: t2 depends on t1, so its worker starts after t1's merge and then waits for
/// t1's two releases, one `POOL_CLEAN_TIMEOUT` each (240 s), and for t2's worktree
/// lease, one engine step. The binding bound is `fake-agent`'s `SH_TIMEOUT` (330 s,
/// `crates/fake-agent/src/headless.rs`, a binary crate, so named here): it cuts the step
/// before the loop's own `wait_for(2)` (`RUN_WAIT + 2 × POOL_CLEAN_TIMEOUT`, 540 s, in
/// 0.1 s polls) can, and 330 s exceeds the 240 s it must cover.
fn wait_gate(gate: &Path) -> Value {
    let polls = wait_for(2).as_millis() / 100;
    sh(&format!(
        "i=0; until [ -e '{}' ]; do i=$((i+1)); [ $i -gt {polls} ] && exit 1; sleep 0.1; done",
        gate.display()
    ))
}

/// Opens `gate` once t1 is merged, neither of its checkouts holds a directory, and t2's
/// worktree lease is decided (a directory held, or its fallback note logged); returns
/// the directory t2's worktree holds. Bounded by `wait_for(2)`: t1's task path and its
/// two releases (the file's header).
fn open_gate_after_t1(h: &RunHarness, id: &str, gate: &Path, wait: Duration) -> Option<String> {
    let held = until("t1's releases and t2's lease", wait, || {
        let run = h.run(id)?;
        if t(&run, "t1").state != TaskState::Merged {
            return None;
        }
        let leases = leases_now(h)?;
        let t1_held = ["t1", "t1.proof"]
            .iter()
            .any(|c| held_by(&leases, c).is_some());
        let held = held_by(&leases, "t2");
        let noted = pool_notes(h, id).iter().any(|n| n == T2_FELL_BACK);
        (!t1_held && (held.is_some() || noted)).then_some(held)
    });
    std::fs::write(gate, b"").unwrap();
    held
}

/// C14: one writer and two task directories (a task worktree and its `.proof` are
/// different owners, decision 4, and the `check` runs in `.proof`). t1's worktree and
/// its `.proof` take both; t2's `.proof` builds in one of them after their release.
///
/// Deviation from the brief (recorded in its implementation notes): `remove_merged`'s
/// releases and t2's `PrepareWorktree` are emitted by the same merge step and run
/// concurrently, and a release cleans before it frees, so t2's worktree may lease while
/// both directories are still t1's and fall back (decision 7: one note, for `t2`).
/// Nothing in the test can order that lease. t2's `.proof` is ordered (task-6 review
/// I1): t2's worker waits, before its `task_done`, for a gate the test opens only once
/// t1 is merged and `leases.json` shows no lease of `t1` or `t1.proof`. Its `.proof`
/// is prepared after `task_done`, so it always finds t1's directories free.
#[test]
fn e2e_a_second_task_reuses_the_released_dir() {
    let h = harness("max_writers = 1\n", "task_dirs = 2\n");
    scripts(&h, "t1", "a.txt");
    let gate = h.dir.path().join("t2-gate");
    h.script(
        "worker-t2-1",
        &[
            commit("b.txt", "x\n"),
            wait_gate(&gate),
            done("added b.txt"),
        ],
    );
    h.script("reviewer-t2-1", &[approve()]);
    let plan = plan_of(&[
        task("t1", &["a.txt"], ""),
        task("t2", &["b.txt"], "deps = [\"t1\"]"),
    ]);
    let id = h.start(&plan, true);
    let t2_worktree_dir = open_gate_after_t1(&h, &id, &gate, wait_for(2));

    let run = h.wait_run(&id, complete, wait_for(2));
    assert_eq!(t(&run, "t2").state, TaskState::Merged);
    let task_dirs = |dirs: Vec<String>| -> Vec<String> {
        dirs.into_iter()
            .filter(|d| d.starts_with("task-"))
            .collect()
    };
    let (t1, t2) = (task_dirs(ran_in(&h, "t1")), task_dirs(ran_in(&h, "t2")));
    assert_eq!(t1.len(), 1, "t1's check built in the pool: {t1:?}");
    assert_eq!(t2.len(), 1, "t2's check built in the pool: {t2:?}");
    let notes = pool_notes(&h, &id);
    match t2_worktree_dir {
        // t2's worktree leased one of t1's released directories, so its `.proof` got
        // the other: decision 5's choice, observed. When the worktree took t1's
        // worktree directory, t2's check builds where t1's check built (F8).
        Some(held) => {
            assert_eq!(notes, Vec::<String>::new());
            let other = if held == "task-1" { "task-2" } else { "task-1" };
            assert_eq!(t2, [other], "t2's worktree holds {held}");
        }
        // The race above (the usual case): one note, for t2's worktree alone, never for
        // its `.proof`. Which of t1's two free directories the `.proof` gets is decision
        // 5's least-recently-used choice between two releases that may end in the same
        // second, so it is not pinned (recorded as a 9.14 follow-up).
        None => assert_eq!(notes, [T2_FELL_BACK]),
    }
}

/// The C14 scenario's one-crate workspace: `pool-bin` prints `v::VALUE`, which each
/// task changes. No dependency, so `cargo run --offline` builds it.
const BIN_WORKSPACE: &[(&str, &str)] = &[
    (
        "Cargo.toml",
        "[package]\nname = \"pool-bin\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    ),
    (
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"pool-bin\"\nversion = \"0.1.0\"\n",
    ),
    (
        "src/main.rs",
        "mod v;\n\nfn main() {\n    println!(\"{}\", v::VALUE);\n}\n",
    ),
    ("src/v.rs", "pub const VALUE: &str = \"base\";\n"),
    ("check.sh", BIN_CHECK_SH),
];

/// The check: never without an explicit `$CARGO_TARGET_DIR`. It sets the sources'
/// mtimes back to 2000 (F8: the incident needs sources older than the previous owner's
/// build), runs the binary, and appends `<checkout> <value> <target dir>` to
/// `$CHECK_LOG`, in the harness's cache directory (writable to a confined check).
const BIN_CHECK_SH: &str = "set -e\n[ -n \"$CARGO_TARGET_DIR\" ]\n\
touch -t 200001010000 src/main.rs src/v.rs\n\
v=$(cargo run --offline -q)\n\
echo \"$(basename \"$PWD\") $v $CARGO_TARGET_DIR\" >> \"$CHECK_LOG\"\n";

fn value(task: &str) -> String {
    format!("pub const VALUE: &str = \"{task}\";\n")
}

/// The C14 scenario's `check_timeout_secs`. Its check compiles and runs the fixture
/// cold: measured 0.5–1.0 s alone, 2.7 s with 8 such builds at once and 4.7 s with 14
/// (`docs/timing-budgets.md`, "Recorded, from M9.14"); 30 s is six times the loaded
/// cost and leaves room for a first exec of `rustc` and the linker.
const BIN_CHECK_TIMEOUT_SECS: u64 = 30;

/// `wait_for(k)` for the C14 scenario: `RUN_WAIT` counts four check or proof runs per
/// task path at the harness's `CHECK_TIMEOUT_SECS` (10 s); each of this scenario's runs
/// may take `BIN_CHECK_TIMEOUT_SECS`, so `k × 4 × (30 − 10)` s more.
fn bin_wait_for(tasks: u32) -> Duration {
    let excess = BIN_CHECK_TIMEOUT_SECS - CHECK_TIMEOUT_SECS;
    wait_for(tasks) + Duration::from_secs(excess * 4) * tasks
}

/// The check lines of `checkout`: `(value, target dir)`.
fn checks_of(log: &Path, checkout: &str) -> Vec<(String, PathBuf)> {
    let text = std::fs::read_to_string(log).unwrap_or_default();
    (text.lines())
        .filter_map(|line| {
            let mut words = line.splitn(3, ' ');
            (words.next()? == checkout).then_some(())?;
            let value = words.next()?.to_string();
            Some((value, PathBuf::from(words.next()?)))
        })
        .collect()
}

/// C14, under the controller's ruling (M9.14.10 implementation notes): t1 then t2 with
/// one writer and two task directories, each changing `v::VALUE` and checking it with
/// real `cargo run --offline`. t1's worker also builds its worktree, so both of t1's
/// directories hold t1's build when they are released; t2's `.proof` is ordered after
/// those releases (the gate above), so wherever it leases, it builds over t1's
/// artifacts with sources older than them: the F8 incident, which only the release
/// clean prevents. Asserted: t2's check ran in a pool `task-<k>` directory (not a
/// fallback), no pool note names `t2.proof`, and it printed t2's value. Not asserted:
/// that it is the directory t1's check used (task 6 deviation 1, task 7 concern 2);
/// asserted instead (task 10 review I2): t1's worker build landed in a pool directory
/// (it logs `t1-build <value> <dir>` only once its binary is there), and t2's check
/// directory is one of t1's build directories, its worktree's or its check's.
#[test]
fn e2e_two_tasks_on_one_pool_dir_the_second_runs_its_own_code() {
    let h = RunHarness::with_config(
        "max_writers = 1\n",
        "[target_pool]\ntask_dirs = 2\n",
        BIN_WORKSPACE,
    );
    let log = h.cache_dir().join("checks.log");
    h.stored_profile(&format!(
        "check = \"sh check.sh\"\ncheck_timeout_secs = {BIN_CHECK_TIMEOUT_SECS}\n\n[env]\nCARGO_TARGET_DIR = \"{{worktree}}/target\"\nCHECK_LOG = {:?}\n",
        log.display().to_string()
    ));
    let build = sh(concat!(
        "set -e; [ -n \"$CARGO_TARGET_DIR\" ]; cargo build --offline -q; ",
        "v=$(\"$CARGO_TARGET_DIR/debug/pool-bin\"); ",
        "echo \"t1-build $v $CARGO_TARGET_DIR\" >> \"$CHECK_LOG\""
    ));
    h.script(
        "worker-t1-1",
        &[commit("src/v.rs", &value("t1")), build, done("t1")],
    );
    h.script("reviewer-t1-1", &[approve()]);
    let gate = h.dir.path().join("t2-gate");
    h.script(
        "worker-t2-1",
        &[
            commit("src/v.rs", &value("t2")),
            wait_gate(&gate),
            done("t2"),
        ],
    );
    h.script("reviewer-t2-1", &[approve()]);
    let plan = plan_of(&[
        task("t1", &["src/v.rs"], ""),
        task("t2", &["src/v.rs"], "deps = [\"t1\"]"),
    ]);
    let id = h.start(&plan, true);
    open_gate_after_t1(&h, &id, &gate, bin_wait_for(2));
    let run = h.wait_run(&id, complete, bin_wait_for(2));
    assert_eq!(t(&run, "t2").state, TaskState::Merged, "{}", report(&run));

    let first = checks_of(&log, "t1.proof");
    assert!(first.iter().all(|(v, _)| v == "t1"), "{first:?}");
    let built = checks_of(&log, "t1-build");
    assert_eq!(built.len(), 1, "t1's worker build landed: {built:?}");
    assert_eq!(built[0].0, "t1", "{built:?}");
    let resolved = |dir: &Path| dir.canonicalize().unwrap_or_else(|_| dir.to_path_buf());
    let t1_dirs: Vec<PathBuf> = (built.iter().chain(&first))
        .map(|(_, dir)| resolved(dir))
        .collect();
    let second = checks_of(&log, "t2.proof");
    assert!(!second.is_empty(), "t2's check ran: {second:?}");
    let pool = pool_root(&h).canonicalize().unwrap();
    let built_in = built[0].1.parent().map(resolved);
    assert_eq!(built_in.as_deref(), Some(pool.as_path()), "{built:?}");
    for (printed, target) in &second {
        let name = target.file_name().and_then(|n| n.to_str()).unwrap_or("");
        let parent = target.parent().and_then(|p| p.canonicalize().ok());
        assert!(
            parent.as_deref() == Some(pool.as_path()) && name.starts_with("task-"),
            "t2's check built in {}, not a pool task directory",
            target.display()
        );
        assert!(
            t1_dirs.contains(&resolved(target)),
            "t2's check built in {}, none of t1's build directories {t1_dirs:?}",
            target.display()
        );
        assert_eq!(printed, "t2", "t2's check ran t1's code (F8)");
    }
    let notes = pool_notes(&h, &id);
    assert!(
        notes.iter().all(|n| n == T2_FELL_BACK),
        "a pool note other than t2's worktree fallback: {notes:?}"
    );
}
